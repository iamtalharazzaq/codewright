# ruff: noqa: E501
"""Package suitable parts as serverless functions (CODEWRIGHT.md 5.18, target: `serverless`), Phase 17.

"Suitable" is mechanical, not guessed: a backend group of the design that owns no table (nothing it does needs to
survive between calls) and orchestrates no saga. Codewright reuses the same analysis as a microservices extraction
(`agent.microservices.extract.plan_extraction`: what other modules call, what the group imports, what can't cross a
process) to find the entry points, then **copies** the group into `services/<name>/`, same as an extraction, but
with a handler per entry point (`event, context -> response`) instead of an RPC router, and a deploy manifest
instead of a Dockerfile. The monolith is never touched: nothing calls the function remotely yet, so there is no
cutover and no anti-corruption layer; wiring a caller to invoke it (and the trigger that starts it) is a runbook
item, the way the canary stages of a microservices cut-over are, because nothing here can start a real deployment.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from agent.decomposition import boundaries as b
from agent.microservices import extract as ex
from agent.microservices.foundation import safe_name

RUNTIME_FOR = {"Python": "python3.12", "Go": "go1.x", "TypeScript": "nodejs20.x", "JavaScript": "nodejs20.x"}


def stateless_groups(design: dict[str, Any]) -> list[str]:
    """Backend groups with no table of their own and no saga to orchestrate: nothing they do needs to survive
    between calls, so they can run as functions instead of a long-lived service."""
    return sorted(
        g["name"] for g in design["groups"] if g["kind"] == "backend" and not g.get("tables") and not g.get("sagas")
    )


def handler_source(package: str, exposed: dict[str, list[str]]) -> str:
    """One handler per group: `{module, function, args, kwargs}` in the event, a JSON-serializable result out.
    Generated by Codewright (CODEWRIGHT.md 5.18); only the functions in EXPOSED can be invoked."""
    return f'''"""Serverless handler for the {package} function (generated by Codewright, CODEWRIGHT.md 5.18).

The trigger (HTTP, a queue, a schedule) is configured in the deploy manifest next to this file, not here: this
module only answers one event with one JSON-serializable result.
"""

from __future__ import annotations

import importlib
from typing import Any

EXPOSED: dict[str, list[str]] = {exposed!r}


def handler(event: dict[str, Any], context: Any = None) -> dict[str, Any]:
    module, function = event.get("module", ""), event.get("function", "")
    if function not in EXPOSED.get(module, []):
        return {{"statusCode": 404, "body": {{"error": f"{{module}}.{{function}} is not exposed"}}}}
    fn = getattr(importlib.import_module(module), function)
    args, kwargs = event.get("args", []), event.get("kwargs", {{}})
    try:
        result = fn(*args, **kwargs)
    except Exception as exc:  # noqa: BLE001  (the caller gets the type and message)
        return {{"statusCode": 500, "body": {{"error": {{"type": type(exc).__name__, "message": str(exc)}}}}}}
    return {{"statusCode": 200, "body": {{"result": result}}}}
'''


def handler_test_source(package: str) -> str:
    return f'''"""The handler answers an exposed function and refuses one that isn't (generated by Codewright)."""

from {package}.handler import EXPOSED, handler


def test_an_unexposed_function_is_refused() -> None:
    assert handler({{"module": "nothing", "function": "here"}})["statusCode"] == 404


def test_every_exposed_function_exists() -> None:
    import importlib

    for module, names in EXPOSED.items():
        loaded = importlib.import_module(module)
        assert all(callable(getattr(loaded, n)) for n in names)
'''


def deploy_manifest(name: str, package: str, exposed: dict[str, list[str]], runtime: str) -> dict[str, Any]:
    """A minimal AWS SAM-style template: one function per exposed name, pointed at the copied package. Reviewed and
    filled in (a real account, a trigger) before it deploys anything; nothing here is applied."""
    resources = {
        f"{safe_name(name)}_{fn}": {
            "Type": "AWS::Serverless::Function",
            "Properties": {
                "CodeUri": f"services/{safe_name(name)}/",
                "Handler": f"{package}.handler.handler",
                "Runtime": runtime,
                "Timeout": 10,
                "MemorySize": 256,
                "Environment": {"Variables": {"CODEWRIGHT_MODULE": module, "CODEWRIGHT_FUNCTION": fn}},
            },
        }
        for module, fns in sorted(exposed.items())
        for fn in fns
    }
    return {
        "AWSTemplateFormatVersion": "2010-09-09",
        "Transform": "AWS::Serverless-2016-10-31",
        "Description": f"Codewright: {name} packaged as serverless functions (CODEWRIGHT.md 5.18). Not deployed.",
        "Resources": resources or {"Placeholder": {"Type": "AWS::Serverless::Function", "Properties": {}}},
    }


def service_dir(name: str) -> str:
    return ex.service_dir(name)


def apply_package(work: Path, plan_x: ex.Plan, roots: list[str], package: str, runtime: str) -> dict[str, str | None]:
    """Copy the group's files (and the unowned files they import) into `services/<name>/src/`, same layout as an
    extraction, then write the handler and the deploy manifest. Returns every file's text before (None = did not
    exist), so `agent.microservices.extract.restore` undoes it exactly."""
    before: dict[str, str | None] = {}
    svc = ex.service_dir(plan_x.service)
    for rel in [*plan_x.files, *plan_x.shared]:
        inner = rel[len(ex.py_root_of(rel, roots)) :].lstrip("/")
        target = work / svc / "src" / inner
        before.setdefault(target.relative_to(work).as_posix(), None)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text((work / rel).read_text(encoding="utf-8"), encoding="utf-8")
    exposed = {b.py_dotted(f, roots): names for f, names in sorted(plan_x.entries.items()) if b.py_dotted(f, roots)}
    pkg_dir = work / svc / "src" / package
    pkg_dir.mkdir(parents=True, exist_ok=True)
    for rel, text in {
        f"{svc}/src/{package}/handler.py": handler_source(package, exposed),  # type: ignore[arg-type]
        f"{svc}/tests/test_handler.py": handler_test_source(package),
        f"{svc}/deploy/template.yaml": _as_yaml(deploy_manifest(plan_x.service, package, exposed, runtime)),  # type: ignore[arg-type]
    }.items():
        target = work / rel
        before.setdefault(rel, target.read_text(encoding="utf-8") if target.is_file() else None)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    return before


def _as_yaml(data: dict[str, Any]) -> str:
    import yaml  # noqa: PLC0415  (only this one file needs it)

    header = "# Generated by Codewright (CODEWRIGHT.md 5.18). Review before deploying; nothing here was applied.\n"
    return header + yaml.safe_dump(data, sort_keys=False)


def brief(name: str, result: dict[str, Any]) -> str:
    status = result["status"]
    if status != "packaged":
        return f"⏭️ **{name}** not packaged: {result.get('reason')}."
    lines = [
        f"✅ **{name}** packaged as serverless function(s) ({result.get('runtime')}).",
        f"- {result.get('copied', 0)} file(s) copied into `services/{safe_name(name)}/`, one handler per entry point, "
        f"a deploy manifest at `services/{safe_name(name)}/deploy/template.yaml`.",
        f"- Exposed: {', '.join(f'`{m}.{f}`' for m, fs in (result.get('exposed') or {}).items() for f in fs) or 'nothing is called by other modules (it is copied as is)'}",
        "- **Not deployed**: no account, trigger or image is configured. The monolith's own copy is untouched: "
        "nothing calls the function yet; wiring a caller (and the trigger) is a manual step, reviewed before it goes live.",
    ]
    return "\n".join(lines)


def report_lines(design: dict[str, Any], results: dict[str, dict[str, Any]]) -> list[str]:
    groups = stateless_groups(design)
    lines = ["**Serverless packaging** (stateless parts: no table, no saga):", "", "| Function | Status | Entry points |", "|---|---|---|"]  # fmt: skip
    for name in groups:
        r = results.get(name) or {"status": "not packaged"}
        entries = sum(len(v) for v in (r.get("exposed") or {}).values())
        lines.append(f"| {name} | {r['status']} | {entries} |")
    if not groups:
        lines.append("| (none; every backend group owns a table or orchestrates a saga) | — | — |")
    lines += ["", "- No function was deployed and no trigger was configured: that stays manual, reviewed before it goes live."]  # fmt: skip
    return lines
