def targets(work: Path, rules: dict[str, Any], producer: str, consumer: str) -> dict[str, list[str]]:
    """file (in `consumer`) → the function names `producer`'s own files call from it: not from the whole codebase
    (that is what an extraction asks), only the one producer → consumer edge the design flags for decoupling."""
    all_files = b.code_files(work)
    roots = b.py_roots(work)
    known = set(all_files)
    producer_files = [f for f in all_files if b.module_for(rules, f) == producer and f.endswith(".py")]
    consumer_files = {f for f in all_files if b.module_for(rules, f) == consumer and f.endswith(".py")}
    out: dict[str, list[str]] = {}
    for rel in producer_files:
        text = (work / rel).read_text(encoding="utf-8", errors="replace")
        members, _star = ex.used_members(rel, text, known, roots, consumer_files)
        for file, member in sorted(members):
            defs = ex.top_level_defs((work / file).read_text(encoding="utf-8", errors="replace"))
            if defs.get(member) in ("function", "async") and member not in out.setdefault(file, []):
                out[file].append(member)
    return out


def subscriber_edit(text: str, event_type: str, names: list[str], marker: str) -> str:
    lines = [
        "",
        marker,
        f"# Generated by Codewright (CODEWRIGHT.md 5.18): registers the function(s) above as the handler of {event_type!r};",
        "# nothing here changes what they do when called directly.",
        "from libs.events.bus import subscribe as _codewright_subscribe",
        *(f"_codewright_subscribe({event_type!r}, {name})" for name in names),
        "",
    ]
    return text.rstrip("\n") + "\n" + "\n".join(lines)


def review_doc(events: list[dict[str, Any]], call_sites: dict[str, dict[str, list[str]]]) -> str:
    lines = [
        "# Event-driven: what still needs a human",
        "",
        "Generated by Codewright (CODEWRIGHT.md 5.18). Codewright wired the safe half of each proposed event (the "
        "registry at `libs/events/bus.py` and the consumer's subscription). Replacing the **producer's** direct "
        "call with `publish(...)` is not automatic: if the call's result is used, turning it into a fire-and-forget "
        "event changes behavior, and only a human can tell the two apart safely. Review each one:",
        "",
    ]
    for e in events:
        found = call_sites.get(e["event"], {})
        lines.append(f"## `{e['event']}`: {e['producer']} → {', '.join(e['consumers'])}")
        if not found:
            lines.append("- No call from the producer's own files to the consumer's functions was found by machine.")
        for consumer_file, names in sorted(found.items()):
            lines.append(
                f"- `{consumer_file}`: {', '.join(names)} — called from `{e['producer']}`'s code today; replace "
                f"the call with `publish({e['event']!r}, {e['producer']!r}, {{...}})` once you've confirmed nothing "
                "uses its return value."
            )
        lines.append("")
    return "\n".join(lines)


REVIEW_DOC_PATH = "docs/architecture/EVENTS_REVIEW.md"
restore = ex.restore  # the same files-before-map undo convention as an extraction or a merge


def apply(work: Path, rules: dict[str, Any], platform: dict[str, Any]) -> tuple[dict[str, str | None], dict[str, Any]]:
    """Write the bus and the envelope (once), register every safe subscription and the review doc. Returns every
    touched file's text before (None = did not exist, for `restore`) and what to say in the brief."""
    before: dict[str, str | None] = {}
    events = platform.get("events", [])
    info: dict[str, Any] = {"events": len(events), "subscribed": {}, "call_sites": {}}
    if not events:
        return before, info
    for rel, text in {"libs/events/envelope.py": fd.ENVELOPE_PY, "libs/events/bus.py": BUS_PY}.items():
        target = work / rel
        if not target.is_file():
            before[rel] = None
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
    for e in events:
        found_all: dict[str, list[str]] = {}
        for consumer in e["consumers"]:
            for file, names in targets(work, rules, e["producer"], consumer).items():
                bucket = found_all.setdefault(file, [])
                bucket.extend(n for n in names if n not in bucket)
        info["call_sites"][e["event"]] = found_all
        for file, names in found_all.items():
            marker = f"# codewright:event-subscriber:{e['event']}"
            text = (work / file).read_text(encoding="utf-8")
            if marker in text:
                continue
            before.setdefault(file, text)
            (work / file).write_text(subscriber_edit(text, e["event"], names, marker), encoding="utf-8")
            info["subscribed"].setdefault(e["event"], []).extend(names)
    doc_target = work / REVIEW_DOC_PATH
    before.setdefault(doc_target.relative_to(work).as_posix(), doc_target.read_text(encoding="utf-8") if doc_target.is_file() else None)  # fmt: skip
    doc_target.parent.mkdir(parents=True, exist_ok=True)
    doc_target.write_text(review_doc(events, info["call_sites"]), encoding="utf-8")
    return before, info


def brief(info: dict[str, Any]) -> str:
    if not info["events"]:
        return "**Event-driven**: the design proposes no events to decouple, so nothing was generated."
    lines = [
        f"**Event-driven**: {info['events']} event(s) from the design; the bus and envelope are real, generated "
        "at `libs/events/`.",
        "",
    ]
    for event, names in info["subscribed"].items():
        lines.append(
            f"- `{event}`: {', '.join(sorted(set(names)))} registered as the handler (safe: nothing that already "
            "runs was changed)."
        )
    total_sites = sum(len(v) for v in info["call_sites"].values())
    lines += [
        "",
        f"⚠️ The producer's {total_sites} direct call(s) were **not** rewritten (a call's result may be used, "
        f"which only a human can judge safely); see `{REVIEW_DOC_PATH}`.",
    ]
    return "\n".join(lines)
