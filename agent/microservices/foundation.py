"""The foundation of a microservices conversion (CODEWRIGHT.md 5.18 step 6), generated from the approved design.

Everything here is a template filled from the design, not model output: a gateway that routes everything to the
monolith first (the Strangler Fig), the broker and tracing for local runs, the event envelope and the JWT check as
small libraries in the languages the services use, and a CI workflow with one job per service. The checks at the end
are static; no image is built here (the sandbox has no Docker daemon, by design) and the report says so.

Layout (CODEWRIGHT.md 5.18): `gateway/`, `platform/`, `libs/`, `services/<name>/` and `docs/` beside the monolith,
which stays where it is until its last route has moved.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

import yaml

PORT = 8000  # inside the containers; every service listens here
GATEWAY_PORT = 8080
PINNED = {
    "gateway": "nginx:1.27-alpine",
    "broker": "nats:2.10-alpine",
    "tracing": "jaegertracing/all-in-one:1.57",
    "db": "postgres:17-alpine",
}
TEMPLATE_FOR = {  # the Language Pack's API template for a service's language (CODEWRIGHT.md 8.4)
    "Python": "api-fastapi",
    "Go": "api-go",
    "TypeScript": "api-node",
    "JavaScript": "api-node",
}
LANG_KEY = {"Python": "python", "Go": "go", "TypeScript": "ts", "JavaScript": "ts"}


def service_names(design: dict[str, Any]) -> list[str]:
    return [g["name"] for g in design["groups"] if g["kind"] == "backend"]


def safe_name(name: str) -> str:
    """A service name usable as a folder, a schema and a Python package."""
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_") or "service"


def host_name(name: str) -> str:
    """The same name as a host name (no underscores)."""
    return safe_name(name).replace("_", "-")


# ── the gateway ──────────────────────────────────────────────────────────────
def routes_for(design: dict[str, Any], live: dict[str, bool] | None = None) -> dict[str, Any]:
    """`gateway/routes.json`: the single source of the gateway's routing. Everything goes to the monolith; a service's
    prefix is routed to it only once its cut-over is approved (`live`, by service name)."""
    live = live or {}
    return {
        "default": "monolith",
        "services": {
            safe_name(n): {"prefix": f"/{host_name(n)}/", "upstream": host_name(n), "live": bool(live.get(n))}
            for n in service_names(design)
        },
    }


def render_nginx(routes: dict[str, Any]) -> str:
    upstreams = [f"    upstream monolith {{ server monolith:{PORT}; }}"]
    locations = []
    for name, r in sorted(routes["services"].items()):
        ident = r["upstream"].replace("-", "_")
        upstreams.append(f"    upstream {ident} {{ server {r['upstream']}:{PORT}; }}")
        if r["live"]:
            locations.append(
                f"        location {r['prefix']} {{  # {name}\n"
                f"            proxy_pass http://{ident}/;\n"
                "            proxy_set_header Host $host;\n"
                "            proxy_set_header X-Request-Id $request_id;\n"
                "        }\n"
            )
    return (
        "# Generated by Codewright from gateway/routes.json (the Strangler Fig: everything goes to the monolith until a\n"
        "# service's cut-over is approved). Authorization and the W3C trace headers pass through unchanged.\n"
        "events {}\nhttp {\n" + "\n".join(upstreams) + "\n    server {\n"
        f"        listen {GATEWAY_PORT};\n"
        + "".join(locations)
        + "        location / {\n            proxy_pass http://monolith;\n            proxy_set_header Host $host;\n"
        "            proxy_set_header X-Request-Id $request_id;\n        }\n    }\n}\n"
    )


# ── libraries: the event envelope and the JWT check ──────────────────────────
ENVELOPE_SCHEMA = {
    "$schema": "https://json-schema.org/draft/2020-12/schema",
    "title": "Event envelope",
    "type": "object",
    "required": ["id", "type", "source", "time", "version", "data"],
    "properties": {
        "id": {"type": "string"},
        "type": {"type": "string", "description": "e.g. order.placed"},
        "source": {"type": "string", "description": "the producing service"},
        "time": {"type": "string", "format": "date-time"},
        "version": {"type": "integer", "minimum": 1},
        "correlation_id": {"type": "string"},
        "data": {"type": "object"},
    },
}
ENVELOPE_PY = '''"""The event envelope every service publishes and consumes (libs/events/envelope.schema.json)."""

from __future__ import annotations

import uuid
from datetime import UTC, datetime
from typing import Any

REQUIRED = ("id", "type", "source", "time", "version", "data")


def envelope(
    type: str, source: str, data: dict[str, Any], correlation_id: str | None = None, version: int = 1
) -> dict[str, Any]:
    return {
        "id": str(uuid.uuid4()),
        "type": type,
        "source": source,
        "time": datetime.now(UTC).isoformat(),
        "version": version,
        "correlation_id": correlation_id or str(uuid.uuid4()),
        "data": data,
    }


def validate(event: dict[str, Any]) -> None:
    missing = [k for k in REQUIRED if k not in event]
    if missing:
        raise ValueError(f"event is missing {', '.join(missing)}")
    if not isinstance(event["data"], dict) or not isinstance(event["version"], int):
        raise ValueError("event data must be an object and version an integer")
'''
ENVELOPE_GO = """// Package events is the event envelope every service publishes and consumes (libs/events/envelope.schema.json).
package events

import (
	"crypto/rand"
	"encoding/hex"
	"errors"
	"time"
)

type Envelope struct {
	ID            string         `json:"id"`
	Type          string         `json:"type"`
	Source        string         `json:"source"`
	Time          string         `json:"time"`
	Version       int            `json:"version"`
	CorrelationID string         `json:"correlation_id,omitempty"`
	Data          map[string]any `json:"data"`
}

func newID() string {
	b := make([]byte, 16)
	_, _ = rand.Read(b)
	return hex.EncodeToString(b)
}

func New(typ, source string, data map[string]any, correlationID string) Envelope {
	if correlationID == "" {
		correlationID = newID()
	}
	return Envelope{ID: newID(), Type: typ, Source: source, Time: time.Now().UTC().Format(time.RFC3339), Version: 1, CorrelationID: correlationID, Data: data}
}

func (e Envelope) Validate() error {
	if e.ID == "" || e.Type == "" || e.Source == "" || e.Time == "" || e.Version < 1 || e.Data == nil {
		return errors.New("event is missing id, type, source, time, version or data")
	}
	return nil
}
"""
ENVELOPE_TS = """// The event envelope every service publishes and consumes (libs/events/envelope.schema.json).
import { randomUUID } from "node:crypto";

export interface Envelope {
  id: string;
  type: string;
  source: string;
  time: string;
  version: number;
  correlation_id?: string;
  data: Record<string, unknown>;
}

export function envelope(type: string, source: string, data: Record<string, unknown>, correlationId?: string): Envelope {
  return { id: randomUUID(), type, source, time: new Date().toISOString(), version: 1, correlation_id: correlationId ?? randomUUID(), data };
}

export function validate(e: Partial<Envelope>): void {
  for (const k of ["id", "type", "source", "time", "version", "data"] as const) {
    if (e[k] === undefined || e[k] === null) throw new Error(`event is missing ${k}`);
  }
}
"""
JWT_PY = '''"""Checks a JWT signed with HS256 (the shared secret is JWT_SECRET). Standard library only."""

from __future__ import annotations

import base64
import hashlib
import hmac
import json
import time
from typing import Any


def _b64(part: str) -> bytes:
    return base64.urlsafe_b64decode(part + "=" * (-len(part) % 4))


def verify(token: str, secret: str, now: float | None = None) -> dict[str, Any]:
    """The token's claims; raises ValueError when the token is malformed, forged or expired."""
    try:
        head, body, sig = token.split(".")
        expected = hmac.new(secret.encode(), f"{head}.{body}".encode(), hashlib.sha256).digest()
        header = json.loads(_b64(head))
        if header.get("alg") != "HS256" or not hmac.compare_digest(expected, _b64(sig)):
            raise ValueError("bad signature")
        claims: dict[str, Any] = json.loads(_b64(body))
    except (ValueError, KeyError, json.JSONDecodeError) as exc:
        raise ValueError("invalid token") from exc
    if "exp" in claims and float(claims["exp"]) < (time.time() if now is None else now):
        raise ValueError("token expired")
    return claims
'''
JWT_GO = """// Package auth checks a JWT signed with HS256 (the shared secret is JWT_SECRET). Standard library only.
package auth

import (
	"crypto/hmac"
	"crypto/sha256"
	"encoding/base64"
	"encoding/json"
	"errors"
	"strings"
	"time"
)

func Verify(token, secret string) (map[string]any, error) {
	parts := strings.Split(token, ".")
	if len(parts) != 3 {
		return nil, errors.New("invalid token")
	}
	mac := hmac.New(sha256.New, []byte(secret))
	mac.Write([]byte(parts[0] + "." + parts[1]))
	sig, err := base64.RawURLEncoding.DecodeString(parts[2])
	if err != nil || !hmac.Equal(mac.Sum(nil), sig) {
		return nil, errors.New("invalid token")
	}
	raw, err := base64.RawURLEncoding.DecodeString(parts[1])
	if err != nil {
		return nil, errors.New("invalid token")
	}
	var claims map[string]any
	if err := json.Unmarshal(raw, &claims); err != nil {
		return nil, errors.New("invalid token")
	}
	if exp, ok := claims["exp"].(float64); ok && exp < float64(time.Now().Unix()) {
		return nil, errors.New("token expired")
	}
	return claims, nil
}
"""
JWT_TS = """// Checks a JWT signed with HS256 (the shared secret is JWT_SECRET). Node's crypto only.
import { createHmac, timingSafeEqual } from "node:crypto";

export function verify(token: string, secret: string): Record<string, unknown> {
  const parts = token.split(".");
  if (parts.length !== 3) throw new Error("invalid token");
  const expected = createHmac("sha256", secret).update(`${parts[0]}.${parts[1]}`).digest();
  const given = Buffer.from(parts[2], "base64url");
  if (expected.length !== given.length || !timingSafeEqual(expected, given)) throw new Error("invalid token");
  const claims = JSON.parse(Buffer.from(parts[1], "base64url").toString("utf-8")) as Record<string, unknown>;
  if (typeof claims.exp === "number" && claims.exp < Date.now() / 1000) throw new Error("token expired");
  return claims;
}
"""
