# ── compose, CI ──────────────────────────────────────────────────────────────
def compose_for(design: dict[str, Any], platform: dict[str, Any], project: str) -> dict[str, Any]:
    """`platform/docker-compose.yml`: the monolith, the gateway, the services, the broker, tracing and the database.
    Secrets come from the environment (`${VAR:?}`); nothing is written into the file."""
    shared_env = {
        "JWT_SECRET": "${JWT_SECRET:?set JWT_SECRET}",
        "OTEL_EXPORTER_OTLP_ENDPOINT": "http://jaeger:4318",
    }
    broker = bool(platform.get("broker"))
    if broker:
        shared_env["NATS_URL"] = "nats://nats:4222"
    compose: dict[str, Any] = {
        "name": host_name(project),
        "services": {
            "gateway": {
                "image": PINNED["gateway"],
                "ports": [f"{GATEWAY_PORT}:{GATEWAY_PORT}"],
                "volumes": ["../gateway/nginx.conf:/etc/nginx/nginx.conf:ro"],
                "depends_on": ["monolith"],
            },
            "monolith": {
                "build": {"context": ".."},
                "environment": {**shared_env, "OTEL_SERVICE_NAME": "monolith"},
                "depends_on": ["db"],
            },
            "jaeger": {
                "image": PINNED["tracing"],
                "ports": ["16686:16686"],
                "environment": {"COLLECTOR_OTLP_ENABLED": "true"},
            },
            "db": {
                "image": PINNED["db"],
                "environment": {"POSTGRES_PASSWORD": "${POSTGRES_PASSWORD:?set POSTGRES_PASSWORD}"},
                "volumes": ["db-data:/var/lib/postgresql/data"],
            },
        },
        "volumes": {"db-data": {}},
    }
    if broker:
        compose["services"]["nats"] = {"image": PINNED["broker"]}
    for name in service_names(design):
        host, schema = host_name(name), safe_name(name)
        compose["services"][host] = {
            "build": {"context": f"../services/{schema}"},
            "environment": {
                **shared_env,
                "OTEL_SERVICE_NAME": host,
                "DATABASE_URL": f"postgresql://svc_{schema}@db:5432/postgres?options=-csearch_path%3D{schema}",
            },
            "depends_on": ["db", *(["nats"] if broker else [])],
        }
        compose["services"]["gateway"]["depends_on"].append(host)
    return compose


def ci_for(design: dict[str, Any], languages: dict[str, str]) -> dict[str, Any]:
    """`.github/workflows/services.yml`: one job per service, running the commands of its language."""
    node = [
        {"uses": "actions/setup-node@v4", "with": {"node-version": "22"}},
        {"run": "npm ci"},
        {"run": "npm test"},
    ]
    steps_for = {
        "Python": [
            {"uses": "actions/setup-python@v5", "with": {"python-version": "3.12"}},
            {"run": 'pip install -e ".[test]"'},
            {"run": "pytest -q"},
        ],
        "Go": [{"uses": "actions/setup-go@v5", "with": {"go-version": "stable"}}, {"run": "go test ./..."}],
        "TypeScript": node,
        "JavaScript": node,
    }
    jobs: dict[str, Any] = {}
    for name in service_names(design):
        lang = languages.get(name, "Python")
        if lang not in steps_for:
            continue
        jobs[host_name(name)] = {
            "runs-on": "ubuntu-24.04",
            "defaults": {"run": {"working-directory": f"services/{safe_name(name)}"}},
            "steps": [{"uses": "actions/checkout@v4"}, *steps_for[lang]],
        }
    return {
        "name": "services",
        "on": {"push": {"paths": ["services/**", "libs/**"]}, "pull_request": {}},
        "jobs": jobs,
    }


def foundation_files(
    design: dict[str, Any], platform: dict[str, Any], languages: dict[str, str], project: str
) -> dict[str, str]:
    """Every file of the foundation, by path."""
    routes = routes_for(design)
    files: dict[str, str] = {
        "gateway/routes.json": json.dumps(routes, indent=2) + "\n",
        "gateway/nginx.conf": render_nginx(routes),
        "platform/docker-compose.yml": yaml.safe_dump(compose_for(design, platform, project), sort_keys=False),
        "platform/README.md": (
            "# Platform\n\nRun the monolith behind the gateway with the broker and tracing:\n\n"
            "```bash\nexport JWT_SECRET=$(openssl rand -hex 32) POSTGRES_PASSWORD=$(openssl rand -hex 16)\n"
            f"docker compose -f platform/docker-compose.yml up --build\n```\n\nOpen http://localhost:{GATEWAY_PORT} "
            "(gateway) and http://localhost:16686 (Jaeger). Everything is routed to the monolith until a service is "
            "cut over.\n"
        ),
        "libs/events/envelope.schema.json": json.dumps(ENVELOPE_SCHEMA, indent=2) + "\n",
        ".github/workflows/services.yml": yaml.safe_dump(ci_for(design, languages), sort_keys=False),
    }
    used = {LANG_KEY[lang] for lang in languages.values() if lang in LANG_KEY} or {"python"}
    for key in used & set(LIBS):
        files.update(LIBS[key])
    return files


# ── static checks ────────────────────────────────────────────────────────────
def check_foundation(files: dict[str, str]) -> list[str]:
    """Problems found in the generated files (empty = clean). Static only: nothing is built or started."""
    problems: list[str] = []
    try:
        compose = yaml.safe_load(files["platform/docker-compose.yml"])
        ci = yaml.safe_load(files[".github/workflows/services.yml"])
    except (KeyError, yaml.YAMLError) as exc:
        return [f"the generated YAML does not parse: {exc}"]
    routes = json.loads(files["gateway/routes.json"])
    ports: list[str] = []
    for name, svc in compose["services"].items():
        image = svc.get("image")
        if image and (":" not in image or image.endswith(":latest")):
            problems.append(f"{name}: image {image} is not pinned to a version")
        ports += [str(p).split(":")[0] for p in svc.get("ports", [])]
        for key, value in (svc.get("environment") or {}).items():
            if re.search(r"(?i)secret|password|token", key) and not str(value).startswith("${"):
                problems.append(f"{name}: {key} has a literal value; read it from the environment")
        if "/var/run/docker.sock" in json.dumps(svc):
            problems.append(f"{name}: mounts the Docker socket")
    if len(ports) != len(set(ports)):
        problems.append("two containers publish the same host port")
    for name, route in routes["services"].items():
        if route["upstream"] not in compose["services"]:
            problems.append(f"the gateway routes {name} to {route['upstream']}, which is not in the compose file")
    for job, spec in ci["jobs"].items():
        if job not in compose["services"]:
            problems.append(f"CI job {job} has no service in the compose file")
        problems += [
            f"CI job {job}: {s['uses']} is not pinned" for s in spec["steps"] if s.get("uses") and "@" not in s["uses"]
        ]
    return problems


def write_files(work: Path, files: dict[str, str]) -> list[str]:
    """Write `files` under `work`, never overwriting a file that exists. Returns the paths written."""
    written = []
    for rel, text in files.items():
        target = work / rel
        if target.exists():
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        written.append(rel)
    return written
